# ITERABLES:-
           # An object/collection that can return its elements one at a time,
           # allowing it to be iterated over in a loop.


numbers = [1,2,3,4,5]

for number in numbers:
    print(number)
# --------------- OR ------------- #
for item in numbers:
    print(item)
# --------------- OR ------------- #

for number in reversed(numbers):
    print(number)

# --------------- NXT ONE ------------- #

fruits = {"apple","banana","mango","litchi","cherry","grapes"}

for fruit in fruits:
    print(fruit)

# --------------- NXT ONE ------------- #

name = "DEAR ZINDAGI"

for character in name:
    print(character)

